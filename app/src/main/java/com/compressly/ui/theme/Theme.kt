/**
 * App theme. A deliberate custom palette (no Material dynamic color) so the
 * app keeps a distinct identity in both light and dark modes. Follows the
 * system by default with a manual override in Settings.
 */
@Composable
fun CompresslyTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    content: @Composable () -> Unit
) {
    val dark = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    MaterialTheme(
        colorScheme = if (dark) DarkColors else LightColors,
        typography = AppTypography,
        shapes = AppShapes,
        content = content
    )
}
